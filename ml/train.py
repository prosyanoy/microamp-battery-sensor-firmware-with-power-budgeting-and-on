"""Train the tiny MLP in NumPy, quantise it to int8 and export C arrays.

    PYTHONPATH=sim:. python -m ml.train        (or: make train)
"""
from __future__ import annotations

import json
import pathlib

import numpy as np

from .dataset import CLASSES, build
from .features import N_FEATURES, quantise

ROOT = pathlib.Path(__file__).resolve().parent.parent
HIDDEN = (24, 12)
REQ_SHIFT = 24
FEAT_SHIFT = 12


def softmax(z):
    e = np.exp(z - z.max(axis=1, keepdims=True))
    return e / e.sum(axis=1, keepdims=True)


def init(rng, sizes):
    return [(rng.normal(scale=np.sqrt(2 / a), size=(b, a)), np.zeros(b))
            for a, b in zip(sizes[:-1], sizes[1:])]


def forward(params, x):
    acts = [x]
    for i, (w, b) in enumerate(params):
        z = acts[-1] @ w.T + b
        acts.append(np.maximum(z, 0) if i < len(params) - 1 else z)
    return acts


def fit(X, y, rng, epochs=40, lr=4e-3, wd=1e-4):
    sizes = [X.shape[1], *HIDDEN, len(CLASSES)]
    params = init(rng, sizes)
    m = [[np.zeros_like(p) for p in layer] for layer in params]
    v = [[np.zeros_like(p) for p in layer] for layer in params]
    cw = len(y) / (len(CLASSES) * np.maximum(np.bincount(y, minlength=3), 1))
    cw = np.sqrt(cw)                                   # soften class re-weighting
    t = 0
    for ep in range(epochs):
        perm = rng.permutation(len(X))
        for s in range(0, len(X), 128):
            idx = perm[s:s + 128]
            acts = forward(params, X[idx])
            p = softmax(acts[-1])
            g = p.copy()
            g[np.arange(len(idx)), y[idx]] -= 1
            g *= (cw[y[idx]] / len(idx))[:, None]
            t += 1
            for li in range(len(params) - 1, -1, -1):
                w, b = params[li]
                gw = g.T @ acts[li] + wd * w
                gb = g.sum(axis=0)
                if li:
                    g = (g @ w) * (acts[li] > 0)
                for k, (grad, par) in enumerate(((gw, w), (gb, b))):
                    m[li][k] = 0.9 * m[li][k] + 0.1 * grad
                    v[li][k] = 0.999 * v[li][k] + 0.001 * grad ** 2
                    par -= lr * (m[li][k] / (1 - 0.9 ** t)) / (np.sqrt(v[li][k] / (1 - 0.999 ** t)) + 1e-8)
    return params


def quantise_model(params, Xq):
    """Post-training int8 quantisation with calibration on Xq (int8 inputs)."""
    s_in = 1.0 / 127.0
    x = Xq.astype(np.float64) * s_in
    layers = []
    for i, (w, b) in enumerate(params):
        z = x @ w.T + b
        last = i == len(params) - 1
        s_w = np.abs(w).max() / 127.0
        s_out = np.abs(z).max() / 127.0 if last else np.maximum(z, 0).max() / 127.0
        wq = np.clip(np.rint(w / s_w), -127, 127).astype(np.int8)
        bq = np.rint(b / (s_in * s_w)).astype(np.int32)
        mult = int(round(s_in * s_w / s_out * (1 << REQ_SHIFT)))
        assert 0 < mult < (1 << 31)
        layers.append({"w": wq, "b": bq, "m": mult, "relu": not last})
        x = np.maximum(z, 0) if not last else z
        s_in = s_out
    return layers


def int_forward(layers, q):
    """Reference of the C kernel (nn_int8.c): int64 accumulate, fixed-point requant."""
    h = np.asarray(q, dtype=np.int64)
    for L in layers:
        acc = L["w"].astype(np.int64) @ h + L["b"].astype(np.int64)
        out = (acc * L["m"] + (1 << (REQ_SHIFT - 1))) >> REQ_SHIFT
        h = np.clip(out, 0 if L["relu"] else -128, 127)
    return h


def predict(layers, Xq):
    logits = np.array([int_forward(layers, q) for q in Xq])
    return logits.argmax(axis=1), logits


def c_array(name, arr, ctype, per=16):
    flat = np.asarray(arr).reshape(-1)
    body = ",\n".join("    " + ", ".join(str(int(v)) for v in flat[i:i + per])
                      for i in range(0, len(flat), per))
    return f"const {ctype} {name}[{len(flat)}] = {{\n{body}\n}};\n"


def export(layers, mult, out_dir: pathlib.Path):
    dims = [N_FEATURES] + [L["w"].shape[0] for L in layers]
    h = ["/* Generated by ml/train.py - do not edit. */",
         "#ifndef MODEL_DATA_H", "#define MODEL_DATA_H", "#include <stdint.h>", "",
         f"#define MODEL_N_LAYERS {len(layers)}",
         f"#define MODEL_N_IN {dims[0]}", f"#define MODEL_N_CLASSES {dims[-1]}",
         f"#define MODEL_MAX_WIDTH {max(dims)}",
         f"#define MODEL_REQ_SHIFT {REQ_SHIFT}", f"#define MODEL_FEAT_SHIFT {FEAT_SHIFT}", ""]
    c = ['/* Generated by ml/train.py - do not edit. */', '#include "model_data.h"', ""]
    h.append("extern const int32_t model_feat_mult[MODEL_N_IN];")
    c.append(c_array("model_feat_mult", mult, "int32_t"))
    h.append(f"extern const uint8_t model_dims[{len(dims)}];")
    c.append(c_array("model_dims", dims, "uint8_t"))
    for i, L in enumerate(layers, 1):
        h.append(f"#define MODEL_L{i}_RELU {int(L['relu'])}")
        h.append(f"#define MODEL_L{i}_MULT {L['m']}")
        h.append(f"extern const int8_t model_w{i}[{L['w'].size}];")
        h.append(f"extern const int32_t model_b{i}[{L['b'].size}];")
        c.append(c_array(f"model_w{i}", L["w"], "int8_t"))
        c.append(c_array(f"model_b{i}", L["b"], "int32_t"))
    h += ["", "#endif", ""]
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "model_data.h").write_text("\n".join(h))
    (out_dir / "model_data.c").write_text("\n".join(c))


def export_golden(layers, mult, rng, path: pathlib.Path):
    """Golden windows (+ expected features/logits) so C tests are bit-exact checks."""
    from .features import extract
    from microamp_sim import scenarios as sc
    from .dataset import training_trace, DECIM
    tr = training_trace(rng, 120.0)
    mg = sc.quantise_mg(tr.acc[::DECIM])
    base = np.rint(np.median(tr.acc[::DECIM][:200], axis=0) * 1000).astype(int)
    picks = []
    for e in tr.events[:6]:
        picks.append(int(e.t_start * 100) - 10)
    picks += [100, 1500]
    out = ["/* Generated by ml/train.py - do not edit. */", "#include <stdint.h>",
           f"#define GOLDEN_N {len(picks)}",
           "static const int16_t golden_baseline[3] = {%s};" % ", ".join(map(str, base))]
    wins, feats, cls, logits = [], [], [], []
    for p in picks:
        w = mg[p:p + 64]
        f = extract(w, base)
        q = quantise(f, mult, FEAT_SHIFT)
        lg = int_forward(layers, q)
        wins.append(w.reshape(-1))
        feats.append(f)
        logits.append(lg)
        cls.append(int(np.argmax(lg)))
    out.append("static const int16_t golden_win[GOLDEN_N][192] = {")
    out += ["  {" + ", ".join(map(str, w)) + "}," for w in wins] + ["};"]
    out.append("static const int32_t golden_feat[GOLDEN_N][16] = {")
    out += ["  {" + ", ".join(map(str, f)) + "}," for f in feats] + ["};"]
    out.append("static const int32_t golden_logits[GOLDEN_N][3] = {")
    out += ["  {" + ", ".join(map(str, l)) + "}," for l in logits] + ["};"]
    out.append("static const uint8_t golden_class[GOLDEN_N] = {%s};" % ", ".join(map(str, cls)))
    path.write_text("\n".join(out) + "\n")


def main():
    rng = np.random.default_rng(42)
    X, y = build(range(24))
    Xv, yv = build(range(100, 108))
    S = np.maximum(np.percentile(np.abs(X), 99.5, axis=0), 8.0)
    mult = np.rint(127.0 / S * (1 << FEAT_SHIFT)).astype(np.int64)
    Xq, Xvq = (np.array([quantise(f, mult, FEAT_SHIFT) for f in a]) for a in (X, Xv))
    params = fit(Xq / 127.0, y, rng)
    layers = quantise_model(params, Xq)
    pf = forward(params, Xvq / 127.0)[-1].argmax(axis=1)
    pq, _ = predict(layers, Xvq)
    acc_f, acc_q = float((pf == yv).mean()), float((pq == yv).mean())
    cm = np.zeros((3, 3), int)
    for a, b in zip(yv, pq):
        cm[a, b] += 1
    n_params = sum(L["w"].size + L["b"].size for L in layers)
    metrics = {"train_windows": int(len(y)), "val_windows": int(len(yv)),
               "val_acc_float": acc_f, "val_acc_int8": acc_q, "classes": CLASSES,
               "confusion_int8": cm.tolist(), "n_params": int(n_params),
               "weight_bytes": int(sum(L["w"].size + 4 * L["b"].size for L in layers))}
    export(layers, mult, ROOT / "firmware" / "model")
    export_golden(layers, mult, np.random.default_rng(5), ROOT / "tests" / "c" / "golden_vectors.h")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "model_metrics.json").write_text(json.dumps(metrics, indent=1) + "\n")
    print(json.dumps(metrics, indent=1))


if __name__ == "__main__":
    main()
